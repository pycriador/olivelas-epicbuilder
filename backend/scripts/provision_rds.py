#!/usr/bin/env python3
"""Provision AIOPS App Model database, app user, and schema on RDS PostgreSQL."""

from __future__ import annotations

import argparse
import asyncio
import os
import secrets
from pathlib import Path
from urllib.parse import quote_plus

import asyncpg

from app.db.ssl import asyncpg_connect_kwargs

DEFAULT_DB_NAME = "aiops_app_model"
DEFAULT_APP_USER = "aiops_app_model_app"
DEFAULT_SCHEMA = "portal"


def _strip_password(value: str) -> str:
    value = value.strip()
    if (value.startswith('"') and value.endswith('"')) or (value.startswith("'") and value.endswith("'")):
        return value[1:-1]
    return value


def _admin_config() -> dict[str, str | int]:
    host = os.environ.get("DB_HOST") or os.environ.get("RDS_ADMIN_HOST")
    user = os.environ.get("DB_USER") or os.environ.get("RDS_ADMIN_USER", "postgres")
    password = os.environ.get("DB_PASSWORD") or os.environ.get("RDS_ADMIN_PASSWORD")
    port = int(os.environ.get("DB_PORT") or os.environ.get("RDS_ADMIN_PORT", "5432"))
    admin_db = os.environ.get("RDS_ADMIN_DATABASE", "postgres")
    if not host or not password:
        raise SystemExit("Missing DB_HOST and DB_PASSWORD (admin credentials) in environment.")
    return {
        "host": host,
        "port": port,
        "user": user,
        "password": _strip_password(password),
        "database": admin_db,
    }


def _write_app_env(
    *,
    backend_env: Path,
    host: str,
    port: int,
    database: str,
    app_user: str,
    app_password: str,
    schema: str,
) -> None:
    lines = [
        "# Generated by scripts/provision_rds.py — do not commit",
        (
            "DATABASE_URL=postgresql+asyncpg://"
            f"{quote_plus(app_user)}:{quote_plus(app_password)}@{host}:{port}/{database}"
        ),
        f"DB_HOST={host}",
        f"DB_PORT={port}",
        f"DB_NAME={database}",
        f"DB_USER={app_user}",
        f"DB_PASSWORD={app_password}",
        f"DB_SCHEMA={schema}",
        "APP_NAME=AIOPS App Model API",
        "CORS_ORIGINS=http://localhost:5173,http://localhost:8080,http://localhost:3000,http://127.0.0.1:5173,http://127.0.0.1:8080",
        "",
    ]
    backend_env.write_text("\n".join(lines), encoding="utf-8")
    backend_env.chmod(0o600)


async def provision(
    *,
    database: str,
    app_user: str,
    schema: str,
    app_password: str | None,
    write_env: bool,
) -> None:
    admin = _admin_config()
    generated_password = app_password or secrets.token_urlsafe(24)

    conn = await asyncpg.connect(
        host=str(admin["host"]),
        port=int(admin["port"]),
        user=str(admin["user"]),
        password=str(admin["password"]),
        database=str(admin["database"]),
        timeout=30,
        **asyncpg_connect_kwargs(),
    )
    try:
        exists = await conn.fetchval("SELECT 1 FROM pg_database WHERE datname = $1", database)
        if not exists:
            await conn.execute(f'CREATE DATABASE "{database}"')
            print(f"created database: {database}")
        else:
            print(f"database already exists: {database}")

        user_exists = await conn.fetchval("SELECT 1 FROM pg_roles WHERE rolname = $1", app_user)
        escaped_password = generated_password.replace("'", "''")
        if not user_exists:
            await conn.execute(
                f"CREATE ROLE {app_user} WITH LOGIN PASSWORD '{escaped_password}'"
            )
            print(f"created role: {app_user}")
        else:
            await conn.execute(
                f"ALTER ROLE {app_user} WITH LOGIN PASSWORD '{escaped_password}'"
            )
            print(f"updated password for role: {app_user}")
    finally:
        await conn.close()

    db_conn = await asyncpg.connect(
        host=str(admin["host"]),
        port=int(admin["port"]),
        user=str(admin["user"]),
        password=str(admin["password"]),
        database=database,
        timeout=30,
        **asyncpg_connect_kwargs(),
    )
    try:
        schema_exists = await db_conn.fetchval(
            "SELECT 1 FROM information_schema.schemata WHERE schema_name = $1",
            schema,
        )
        if not schema_exists:
            await db_conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
            print(f"created schema: {schema}")
        else:
            print(f"schema already exists: {schema}")

        await db_conn.execute(f"GRANT CONNECT ON DATABASE {database} TO {app_user}")
        await db_conn.execute(f'GRANT USAGE, CREATE ON SCHEMA "{schema}" TO {app_user}')
        await db_conn.execute(
            f'ALTER DEFAULT PRIVILEGES IN SCHEMA "{schema}" '
            f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {app_user}"
        )
        await db_conn.execute(
            f'ALTER DEFAULT PRIVILEGES IN SCHEMA "{schema}" '
            f"GRANT USAGE, SELECT ON SEQUENCES TO {app_user}"
        )
        await db_conn.execute(f'ALTER ROLE {app_user} SET search_path TO "{schema}", public')
        print("grants applied")
    finally:
        await db_conn.close()

    if write_env:
        backend_root = Path(__file__).resolve().parents[1]
        _write_app_env(
            backend_env=backend_root / ".env",
            host=str(admin["host"]),
            port=int(admin["port"]),
            database=database,
            app_user=app_user,
            app_password=generated_password,
            schema=schema,
        )
        print(f"wrote app credentials to {backend_root / '.env'}")
    else:
        print("APP_PASSWORD (store in backend/.env):", generated_password)


def main() -> None:
    parser = argparse.ArgumentParser(description="Provision AIOPS App Model on RDS PostgreSQL")
    parser.add_argument("--database", default=os.environ.get("APP_DATABASE_NAME", DEFAULT_DB_NAME))
    parser.add_argument("--app-user", default=os.environ.get("APP_DB_USER", DEFAULT_APP_USER))
    parser.add_argument("--schema", default=os.environ.get("DB_SCHEMA", DEFAULT_SCHEMA))
    parser.add_argument("--app-password", default=os.environ.get("APP_DB_PASSWORD"))
    parser.add_argument("--no-write-env", action="store_true")
    args = parser.parse_args()
    asyncio.run(
        provision(
            database=args.database,
            app_user=args.app_user,
            schema=args.schema,
            app_password=args.app_password,
            write_env=not args.no_write_env,
        )
    )


if __name__ == "__main__":
    main()
